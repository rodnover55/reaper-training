#pragma once

// Компонент окна: узел дерева отрисовки.

#include "training/render/frame.hpp"

namespace training::render {

/// Компонент окна — узел дерева отрисовки. Все компоненты проекта
/// реализуют этот интерфейс.
///
/// Компонент рисует себя только примитивами холста кадра и только в месте,
/// которое ему отвёл кадр (`Frame::area`): размеры, кегли и места детей он
/// выводит из этого места сам.
///
/// Что компонент показывает — его состояние. Состояние меняется функциями
/// изменения состояния конкретного компонента; рисование его не меняет, поэтому
/// `draw` константен и один компонент можно нарисовать в одном кадре
/// несколько раз в разных местах.
///
/// Дети лежат у компонента полями; место ребёнку отводит родитель через
/// `Frame::within`. Один вид компонента служит разным элементам дизайна:
/// заливка — и фону строки, и полосе шкалы.
class Element {
public:
  /// Создаёт компонент; своего состояния у `Element` нет.
  Element() = default;

  /// Позволяет удалять компонент через указатель на `Element`.
  virtual ~Element() = default;

  /// Копии нет: компонент — узел своего дерева.
  Element(const Element &) = delete;

  /// Присваивания копией нет: компонент — узел своего дерева.
  Element &operator=(const Element &) = delete;

  /// Присваивания перемещением нет: компонент по базовому классу не
  /// подменить.
  Element &operator=(Element &&) = delete;

  /// Рисует компонент по его состоянию в месте `frame.area` холста
  /// `frame.canvas`.
  virtual void draw(const Frame &frame) const = 0;

protected:
  /// Перемещение открыто только наследникам: компонент по базовому классу не
  /// переместить и не срезать до `Element`, а конкретный компонент
  /// перемещается целиком — так дети лежат в векторах родителя.
  Element(Element &&) = default;
};

} // namespace training::render
