#pragma once

// Петля проекта: время ноты внутри петли и длина петли для строк тактов
// (`timing-display`). На переходе петли хост начинает следующий блок на длину
// петли раньше, и граница петли лежит внутри блока: время ноты, посчитанное от
// позиции блока, может выйти за конец петли.

#include "training/grid/mode.hpp"
#include "training/grid/timeline.hpp"

namespace training::trainer {

/// Петля проекта.
struct Loop {
  /// Правда, если повтор включён.
  bool repeat = false;

  /// Начало и конец петли на шкале проекта, с.
  double start = 0.0;
  double end = 0.0;
};

/// Время ноты на шкале проекта, завёрнутое в петлю с повтором.
///
/// Время заворачивается, если повтор включён, у петли есть длина и позиция
/// блока ноты в петле, границы включительно. Окно заворота сдвинуто назад на
/// половину интервала между узлами режима `mode` у начала петли: узел на конце
/// петли — первый узел следующего прохода, и ранняя нота к первой доле петли
/// остаётся у её начала.
///
/// @param time время ноты, с.
/// @param position позиция обработки блока, в котором пришла нота, с.
/// @param loop петля проекта.
/// @param mode режим сетки.
/// @param timeline карта темпа проекта.
/// @return время в окне заворота; если время не заворачивается, — `time`.
double loopWrapped(double time, double position, const Loop &loop, grid::Mode mode,
                   const grid::Timeline &timeline);

/// Длина петли в ударах для свода нот в строки (`grid::Bars::play`).
///
/// @param position слышимая позиция воспроизведения, с.
/// @return удары от начала до конца петли, если повтор включён, у петли есть
///   длина и позиция в петле, границы включительно; иначе 0.
double loopBeats(double position, const Loop &loop, const grid::Timeline &timeline);

} // namespace training::trainer
