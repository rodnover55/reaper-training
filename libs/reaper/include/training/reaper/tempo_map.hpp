#pragma once

// Карта темпа хоста: такты, их доли и время шкалы.

#include "training/core/clock.hpp"
#include "training/core/training/state/timeline.hpp"

#include <cstdint>
#include <map>

namespace training::reaper {

/// Место на шкале карты темпа: такт и доля в нём.
struct Position {
  /// Такт карты: 0 — первый, его номер для показа — 1; такты раньше
  /// первого — отрицательные.
  std::int64_t bar = 0;

  /// Доля от начала такта в ударах, дробная: 0 — первый удар, 2.5 — середина
  /// третьего.
  double beat = 0.0;
};

/// Такт карты темпа.
struct MapBar {
  /// Такт карты: 0 — первый, его номер для показа — 1.
  std::int64_t index = 0;

  /// Размер такта: число ударов и их длительность.
  core::training::state::Meter meter;

  /// Темп такта по долям. Ключ — доля от начала такта; значение — темп,
  /// которым темп становится на этой доле, четвертей в минуту, как у хоста; у
  /// плавного перехода — темп в конце перехода. Доля 0 есть всегда: её
  /// значение — темп, действующий в начале такта.
  std::map<core::training::state::Beat, double> tempo;
};

/// Карта темпа: перевод между временем шкалы и позициями — тактами и
/// долями — и такты. Удар — единица знаменателя размера, как у метронома
/// хоста.
///
/// Реализация в модуле расширения спрашивает карту темпа хоста, в тестах —
/// считает по заданным темпам и размерам.
class TempoMap {
public:
  /// Позволяет удалять реализацию через указатель на `TempoMap`.
  virtual ~TempoMap() = default;

  /// Создаёт карту; своих данных у `TempoMap` нет, их хранит реализация.
  TempoMap() = default;

  /// Создаёт копию карты; данные копирует реализация, у `TempoMap` их нет.
  TempoMap(const TempoMap &) = default;

  /// Присваивает карте копию другой; данные копирует реализация, у
  /// `TempoMap` их нет.
  TempoMap &operator=(const TempoMap &) = default;

  /// Создаёт карту из перемещаемой; данные переносит реализация, у
  /// `TempoMap` их нет.
  TempoMap(TempoMap &&) = default;

  /// Присваивает карте перемещаемую; данные переносит реализация, у
  /// `TempoMap` их нет.
  TempoMap &operator=(TempoMap &&) = default;

  /// Позиция во время `time` шкалы: такт и доля в нём, от 0 до числа ударов
  /// такта. Время ровно на границе такта может прийти концом прошлого такта:
  /// долей «3.9999…» вместо доли 0 следующего.
  virtual Position positionAt(core::Moment time) const = 0;

  /// Время шкалы позиции `position`. Доля может выходить за такт: она
  /// отсчитывается от начала такта `position.bar` по карте, и доля, равная
  /// числу ударов такта, — начало следующего такта.
  virtual core::Moment timeAt(Position position) const = 0;

  /// Такт номер `index`: его размер и темп по долям.
  virtual MapBar barOf(std::int64_t index) const = 0;
};

} // namespace training::reaper
