// Карта темпа запуска транспорта REAPER во времени ядра (`timing-display`,
// `hit-timing`): такты по порядку запуска и такты для ядра — с долями сетки и
// подписями на экране.

#include "training/core/clock.hpp"
#include "training/core/training/state/timeline.hpp"
#include "training/reaper/count_in.hpp"
#include "training/reaper/mode.hpp"
#include "training/reaper/project_time.hpp"
#include "training/reaper/tempo_map.hpp"

#include <cstddef>
#include <cstdint>
#include <optional>
#include <vector>

namespace training::reaper {

/// Петля проекта с повтором: позиции её начала и конца на шкале проекта.
struct ProjectLoop {
  /// Начало петли.
  core::Moment start;

  /// Конец петли; позже начала.
  core::Moment end;

  /// Правда, если у петель совпадают начало и конец.
  friend bool operator==(const ProjectLoop &, const ProjectLoop &) = default;
};

/// Карта темпа запуска транспорта REAPER во времени ядра и такты запуска для
/// ядра.
///
/// - **Время.** Время блока звука — время ядра его первого сэмпла, которое
///   ставит хук. На отрезке воспроизведения позиция проекта во время `t` —
///   позиция блока, начавшего отрезок, плюс путь от его времени по скорости.
/// - **Начало.** Первый отрезок — связка запуска (`start`): время проекта
///   начала и время ядра T0, с которого звучит позиция начала. Карта готова
///   сразу.
/// - **Отсчёт.** До конца отсчёта REAPER держит позицию блоков на позиции
///   начала, а отсчёт кончается в T0. Позиции раньше позиции начала лежат в
///   тактах сетки отсчёта (`CountInTimeline`).
/// - **Отрезки.** Блок, позиция которого продолжает отрезок, ничего не
///   меняет. Блок с другой позицией — петля, перемотка — начинает новый
///   отрезок, и такты нумеруются по порядку запуска: такты нового отрезка
///   получают номера после последнего такта прошлого. Блок с другой
///   скоростью тоже начинает отрезок, а номера тактов продолжаются.
/// - **Удержание.** После перемотки REAPER несколько блоков держит позицию
///   на месте перехода. Такой блок не начинает отрезок, а переносит начало
///   нового отрезка на себя: звук с места перехода идёт с последнего
///   удержанного блока, как с позиции начала после отсчёта. Первый такт
///   отрезка начинается с первого его блока, чтобы целиком накрыть такт,
///   переданный до переноса.
/// - **Петля.** Пока задана петля с повтором (`setLoop`), отрезок, который
///   дойдёт до её конца, продолжается предсказанным отрезком с её начала
///   (`predict`): такты после конца петли — такты её начала, ещё до того,
///   как переход случился. Блок перехода подтверждает предсказание. Блок,
///   который ему противоречит, и смена петли отменяют предсказанные
///   отрезки.
/// - **Подписи.** Такт запуска подписывается номером такта проекта. Такт
///   начальных отрезков — до первой петли или перемотки — раньше такта,
///   которым кончается затакт, подписывается номером от него назад со знаком
///   минус U+2212: «−1», «−2».
///
/// Созданный объект: запуска нет, карта — карта проекта.
///
/// Многопоточность: только главный поток — карта проекта зовёт REAPER.
class RunTimeline final : public TempoMap {
public:
  /// @param project карта темпа проекта; живёт дольше этой карты.
  explicit RunTimeline(const TempoMap &project);

  /// Начинает запуск: прошлые отрезки забываются, первый отрезок — связка
  /// запуска `start`.
  ///
  /// @param start связка запуска: время проекта начала — позиция обработки в
  ///   момент начала и скорость, больше нуля, — и время ядра T0, с которого
  ///   звучит позиция начала.
  /// @param countIn отсчёт перед запуском: он кончается в T0.
  /// @param leadInEnd такт проекта, которым кончается затакт; пусто —
  ///   затакта нет.
  /// @param sampleRate частота звуковой карты, Гц: такт позиции начала
  ///   (`barAt`).
  void start(RunStart start, const CountIn &countIn, std::optional<std::int64_t> leadInEnd,
             double sampleRate);

  /// Отмечает блок воспроизведения запуска. Блоки раньше T0 — тихие блоки и
  /// отсчёт — ничего не меняют.
  ///
  /// @param time время блока во времени ядра.
  /// @param place время проекта блока: позиция обработки блока REAPER на
  ///   шкале проекта и скорость воспроизведения.
  /// @return такт запуска, с которого такты для ядра (`barAt`) изменились и
  ///   их пора передать заново: после петли или перемотки — первый такт
  ///   нового отрезка, после смены скорости — такт после того, в котором она
  ///   сменилась; пусто — такты прежние.
  std::optional<std::int64_t> addBlock(core::Moment time, ProjectTime place);

  /// Ставит петлю проекта с повтором. Смена петли отменяет предсказанные
  /// отрезки.
  ///
  /// @param loop петля; пусто — повтора нет.
  /// @return такт запуска, с которого такты для ядра изменились, — первый
  ///   такт первого отменённого отрезка; пусто — такты прежние.
  std::optional<std::int64_t> setLoop(std::optional<ProjectLoop> loop);

  /// Продолжает последний отрезок предсказанными отрезками с начала петли
  /// (`setLoop`), пока он доходит до её конца не позже `until`. Без петли,
  /// с петлёй короче 10 мс и у отрезка, который начался после её конца,
  /// ничего не меняет.
  ///
  /// @param until время ядра, до которого карта должна знать переходы петли.
  void predict(core::Moment until);

  /// Время ядра слышимой позиции REAPER — для строк тактов
  /// (`render::BarRows::setBars`). Из отрезков, где эта позиция есть, — тот,
  /// где время ближе к `now`: после петли позиция прошлого прохода ещё
  /// слышна.
  ///
  /// @param heard слышимое время проекта: позиция на шкале проекта и скорость
  ///   воспроизведения.
  /// @param now конец взятого звука во времени ядра.
  core::Moment heard(ProjectTime heard, core::Moment now) const;

  /// Такт запуска и доля во время ядра `time`.
  Position positionAt(core::Moment time) const override;

  /// Время ядра позиции `position` в такте запуска.
  core::Moment timeAt(Position position) const override;

  /// Такт запуска номер `index`: размер и темп такта проекта, номер —
  /// `index`.
  MapBar barOf(std::int64_t index) const override;

  /// Первый такт запуска — тот, в котором лежит начало отсчёта по тактам (его
  /// первый клик), а без отсчёта — позиция начала; начало на границе такта
  /// или не больше чем на 25 мс раньше неё лежит в такте после неё.
  std::int64_t firstBar() const;

  /// Такт запуска номер `index` для ядра (`core::training::Trainer::addBar`).
  ///
  /// - `name` — подпись такта (см. «Подписи»).
  /// - `start` — время первого удара такта; у первого такта отрезка после
  ///   петли или перемотки — время первого блока отрезка (см. «Удержание»).
  /// - `divisions` — доли сетки режима `mode` (`divisions(mode)` долей на
  ///   удар) с временем по этой карте, не раньше `start`.
  /// - `meter` и `tempo` — размер и темп такта (`barOf`).
  core::training::state::Bar barAt(std::int64_t index, Mode mode) const;

private:
  /// Отрезок воспроизведения: время его начала и время проекта там —
  /// позиция и скорость; такт запуска — такт проекта плюс `offset`.
  struct Segment {
    core::Moment time;
    ProjectTime place;
    std::int64_t offset = 0;
    // Первый такт запуска отрезка; у первого отрезка — самый малый номер.
    std::int64_t firstBar = 0;
    // Позиции отрезка раньше позиции начала — в тактах сетки отсчёта.
    bool countIn = false;
    // Отрезок до первой петли или перемотки запуска: у его тактов есть
    // затакт.
    bool initial = true;
    // Отрезок начат петлёй или перемоткой: его первый такт сыгран с места
    // начала отрезка.
    bool jump = false;
    // Время первого блока отрезка: удержание переносит `time` позже него.
    core::Moment from;
    // Позиция отрезка уже пошла дальше места его начала: удержания больше
    // нет.
    bool moving = false;
    // Отрезок предсказан по петле, и блок перехода его ещё не подтвердил.
    bool predicted = false;
  };

  /// Карта темпа отрезка: сетка отсчёта или карта проекта.
  const TempoMap &mapOf(const Segment &segment) const;

  /// Позиция проекта во время `time` на отрезке `segment`.
  static core::Moment projectAt(const Segment &segment, core::Moment time);

  /// Время ядра позиции проекта `position` на отрезке `segment`.
  static core::Moment timeOn(const Segment &segment, core::Moment position);

  /// Отрезок времени `time`: последний, начавшийся не позже него, а раньше
  /// всех — первый.
  const Segment &segmentAt(core::Moment time) const;

  /// Отрезок такта запуска `bar`: последний, чей первый такт не больше него.
  const Segment &segmentOf(std::int64_t bar) const;

  /// Номер отрезка времени `time` в `segments_`, как у `segmentAt`.
  std::size_t indexAt(core::Moment time) const;

  /// Убирает отрезки после номера `index` — они предсказаны по прежнему
  /// пути воспроизведения.
  ///
  /// @return первый такт первого убранного отрезка; пусто — убирать нечего.
  std::optional<std::int64_t> dropAfter(std::size_t index);

  const TempoMap &project_;
  std::optional<CountInTimeline> countIn_;
  CountIn countInLength_;
  std::optional<std::int64_t> leadInEnd_;
  std::optional<ProjectLoop> loop_;
  double sampleRate_ = 0.0;
  std::vector<Segment> segments_;
};

} // namespace training::reaper
