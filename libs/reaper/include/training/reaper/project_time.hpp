#pragma once

// Время проекта REAPER: позиция на шкале проекта вместе со скоростью
// воспроизведения (`timing-display`, `hit-timing`).

#include "training/core/clock.hpp"

namespace training::reaper {

/// Время проекта REAPER — цельная единица из двух полей: позиция на шкале
/// проекта и скорость воспроизведения, с которой позиция идёт.
struct ProjectTime {
  /// Позиция на шкале проекта: секунды от начала проекта от точки отсчёта
  /// `core::Moment()`.
  core::Moment position;

  /// Скорость воспроизведения; больше нуля, 1 — обычная.
  double rate = 1.0;
};

/// Связка запуска транспорта: время проекта начала запуска и назначенное ему
/// время ядра. С этого времени ядра звучит позиция начала — после отсчёта, если
/// он есть.
struct RunStart {
  /// Время проекта начала запуска: позиция начала P0 и скорость.
  ProjectTime start;

  /// Время ядра T0, назначенное времени проекта начала.
  core::Moment time;
};

} // namespace training::reaper
