#pragma once

#include "training/grid/mode.hpp"
#include "training/grid/timeline.hpp"

#include <cstddef>
#include <cstdint>
#include <deque>
#include <optional>
#include <vector>

namespace training::grid {

/// Узел удара в строке.
struct Slot {
  /// Отклонение ноты узла, реальные секунды: минус — раньше узла. Пусто — нота
  /// ещё не пришла или узел пропущен.
  std::optional<double> deviation;

  /// Узел пропущен: время, когда к нему могла относиться нота, прошло, а нот
  /// не было.
  bool missing = false;

  /// К узлу пришло больше одной ноты; в `deviation` — ближайшая к узлу.
  bool extra = false;
};

/// Строка удара: узлы одного удара метронома, в котором сыграна хотя бы одна
/// нота.
struct BeatRow {
  /// Удар от начала проекта (0 — первый удар проекта).
  std::int64_t beat = 0;

  /// Такт и удар в такте для подписи строки.
  BarBeat label;

  /// Режим, в котором удар начался; не меняется до конца удара.
  Mode mode = Mode::Quarters;

  /// Узлы удара по порядку; их `divisions(mode)`.
  std::vector<Slot> slots;

  /// Все узлы решены: в каждом нота или пропуск.
  bool complete = false;

  /// Время удара прошло: момент из `Beats::advance` ушёл за середину между
  /// последним узлом удара и первым узлом следующего. Новые ноты этого удара
  /// — уже следующий проход петли.
  bool closed = false;

  /// Среднее отклонение сыгранных нот, реальные секунды. Есть, когда удар
  /// решён и в нём больше одного узла; пропуски и лишние ноты не входят.
  std::optional<double> mean;

  /// Среднее квадратическое отклонение сыгранных нот от `mean`, реальные
  /// секунды; есть вместе с `mean`.
  std::optional<double> spread;
};

/// Свод нот в строки ударов (design.md D6).
///
/// Строки хранятся новыми вперёд — в порядке, в каком заведены, — не больше
/// `keep`. Удар без нот строки не получает. Смена режима действует на удары,
/// которые начнутся после неё.
///
/// Многопоточность: один поток вызовов.
class Beats {
public:
  /// Создаёт пустой свод: режим «четверти», строк нет.
  ///
  /// @param keep сколько последних строк хранить; больше нуля.
  explicit Beats(std::size_t keep = 8);

  /// Режим для ударов, у которых ещё нет строки.
  void setMode(Mode mode) { mode_ = mode; }

  /// Режим для новых ударов.
  Mode mode() const { return mode_; }

  /// Кладёт ноту в узел, ближайший к `time`, в строке его удара. Строки нет
  /// или время её удара уже прошло (`closed`) — новый проход петли — заводит
  /// новую строку сверху. Если в узле уже есть нота, остаётся ближайшая к
  /// узлу, а узел получает отметку `extra`.
  ///
  /// @param time время ноты на шкале, с.
  /// @param rate скорость воспроизведения проекта; отклонение на шкале
  ///   делится на неё и хранится в реальных секундах.
  void addNote(double time, double rate, const Timeline &timeline);

  /// Отмечает пропущенными узлы, к которым после момента `now` нота уже не
  /// отнесётся: `now` ушёл за середину между узлом и следующим. Решённые
  /// строки получают среднее и разброс.
  ///
  /// @param now время шкалы, с, до которого ноты уже пришли.
  void advance(double now, const Timeline &timeline);

  /// Забывает все строки; режим остаётся.
  void clear() { rows_.clear(); }

  /// Строки, новые вперёд.
  const std::deque<BeatRow> &rows() const { return rows_; }

private:
  std::size_t keep_;
  Mode mode_ = Mode::Quarters;
  std::deque<BeatRow> rows_;
};

} // namespace training::grid
