namespace training::grid {

/// Узел удара в строке такта.
struct RowSlot {
  /// Отклонение ноты узла, реальные секунды: минус — раньше узла. Пусто — ноты
  /// у узла нет.
  std::optional<double> deviation;

  /// К узлу пришло больше одной ноты; в `deviation` — ближайшая к узлу.
  bool extra = false;

  /// Окно попадания, которое действовало, когда появилось значение
  /// `deviation`.
  HitWindow window;
};

/// Удар строки такта.
struct RowBeat {
  /// Режим удара; пусто — удар ещё не начался, узлов у него нет (design.md D4).
  std::optional<Mode> mode;

  /// Узлы удара по порядку: `divisions(*mode)` штук, пусто, пока удар не
  /// начался.
  std::vector<RowSlot> slots;
};

/// Строка такта: один проход воспроизведения через такт (design.md D1).
struct BarRow {
  /// Такт строки: номер, первый удар, размер и смены темпа и размера.
  Bar bar;

  /// Удары такта по порядку, их `bar.meter.beats`.
  std::vector<RowBeat> beats;

  /// Воспроизведение вошло в такт. Строку без этой отметки завела ранняя нота
  /// к такту, который ещё не начался; её не показывают (design.md D3).
  bool entered = false;

  /// Строку свернула пауза в игре: её место заняла строка следующего такта.
  /// Свёрнутую строку не показывают, пока в неё не придёт значение (design.md
  /// D1).
  bool folded = false;

  /// Окно попадания, которое действовало, когда воспроизведение ушло из
  /// такта; пусто, пока не ушло.
  std::optional<HitWindow> leftWindow;

  /// Среднее отклонение значений строки, реальные секунды; есть, когда
  /// значений больше одного. Лишние ноты не входят: у узла одно значение.
  std::optional<double> mean;

  /// Среднее квадратическое отклонение значений строки от `mean`, реальные
  /// секунды; есть вместе с `mean`.
  std::optional<double> spread;

  /// Правда, если хотя бы у одного узла строки есть значение.
  bool hasValues() const;
};

/// Свод нот в строки тактов (design.md D1–D5).
///
/// Строки хранятся новыми вперёд. Видны строки, в такт которых вошло
/// воспроизведение и которые не свёрнуты паузой; таких хранится не больше
/// `keep`. Верхняя видимая строка — такт, в котором сейчас воспроизведение.
///
/// Многопоточность: один поток вызовов.
class Bars {
public:
  /// Создаёт пустой свод: режим «четверти», строк нет, воспроизведения нет.
  ///
  /// @param keep сколько видимых строк хранить; меньше единицы считается
  ///   единицей.
  explicit Bars(std::size_t keep = 8);

  /// Задаёт режим для ударов, которые ещё не начались (design.md D4).
  void setMode(Mode mode) { mode_ = mode; }

  /// Режим для ударов, которые ещё не начались.
  Mode mode() const { return mode_; }

  /// Сообщает позицию воспроизведения, которую сейчас слышно (design.md D2).
  ///
  /// Вход в другой такт или прыжок позиции назад больше чем на полудара
  /// (петля, перемотка) заводит строку сверху: свободную строку ранней ноты
  /// этого такта или новую. Уходящая строка запоминает окно попадания. Если она без
  /// значений, а видимая строка под ней — тоже, уходящая сворачивается, и
  /// новая встаёт на её место. Удары верхней строки до позиции включительно,
  /// ещё не начатые, начинаются в текущем режиме.
  ///
  /// @param beats позиция в ударах от начала проекта, дробная, с заворотом в
  ///   петлю.
  /// @param loopBeats длина петли в ударах, если позиция в петле с повтором;
  ///   иначе 0.
  /// @param window окно попадания на этот момент.
  /// @return правда, если сверху встала строка другого такта или нового
  ///   прохода.
  bool play(double beats, double loopBeats, const HitWindow &window, const Timeline &timeline);

  /// Отмечает остановку воспроизведения: текущего удара больше нет, строки
  /// остаются. Следующий `play` не считается прыжком назад.
  void stop();

  /// Кладёт ноту в ближайший узел (design.md D3).
  ///
  /// Узел ищется среди узлов удара ноты по режиму удара в его строке (или по
  /// текущему режиму, если удар не начался) и первого узла следующего удара.
  /// Строка — по месту узла относительно последней позиции из `play`, по
  /// кругу петли, если она есть: узел на позиции или позади неё — строка
  /// прохода, в котором позиция его прошла; впереди не дальше чем на удар —
  /// верхняя строка, если узел в её такте и в её проходе, иначе строка ранней
  /// ноты для этого такта, которую `play` отдаст при входе. Нота без такой
  /// строки, далеко впереди позиции или до первого `play` не кладётся никуда.
  ///
  /// Если у узла уже есть значение, остаётся ближайшее к узлу, а узел
  /// получает отметку лишней ноты. Значение запоминает окно попадания. Свёрнутая
  /// строка, получив значение, снова видна.
  ///
  /// @param time время ноты на шкале, с.
  /// @param rate скорость воспроизведения проекта, больше нуля: отклонение на
  ///   шкале делится на неё и хранится в реальных секундах.
  /// @param window окно попадания на этот момент.
  void addNote(double time, double rate, const HitWindow &window, const Timeline &timeline);

  /// Забывает все строки и позицию воспроизведения; режим остаётся.
  void clear();

  /// Все строки, новые вперёд, в том числе невидимые: строки ранних нот и
  /// свёрнутые.
  const std::deque<BarRow> &rows() const { return rows_; }

  /// Удар верхней видимой строки, на котором сейчас воспроизведение, с 0;
  /// пусто — воспроизведения нет.
  std::optional<int> currentBeat() const { return currentBeat_; }

private:
  BarRow *currentRow();
  BarRow *rowFor(const Bar &bar, double nodeBeats, bool create);
  void enter(const Bar &bar, const HitWindow &window);
  void trim();

  std::size_t keep_;
  Mode mode_ = Mode::Quarters;
  std::deque<BarRow> rows_;
  std::optional<double> position_;
  double loopBeats_ = 0.0;
  std::optional<int> currentBeat_;
};

} // namespace training::grid
