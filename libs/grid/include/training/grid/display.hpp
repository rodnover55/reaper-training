#pragma once

#include "training/grid/bars.hpp"

#include <optional>
#include <string>
#include <vector>

namespace training::grid {

/// Цвет числа в окне.
enum class Tone {
  /// Без оценки: пропуск, разброс, подпись.
  Neutral,
  /// В окне попадания.
  Good,
  /// Вне окна попадания.
  Bad,
  /// Ровно в смещение: число не дальше 0.5 мс от смещения окна попадания.
  /// Такое число всегда в окне.
  Target,
};

/// Число или знак в окне вместе с цветом.
struct Cell {
  std::string text;
  Tone tone = Tone::Neutral;
};

/// Значение узла в строке такта.
struct ValueView {
  /// Место узла в ударах от начала такта: 0 — первый удар, 1.5 — середина
  /// второго.
  double beat = 0.0;

  /// Узел стоит на ударе: значение показывается крупнее значений между
  /// ударами.
  bool onBeat = false;

  /// Отклонение: «−15», «+5», «0», «+3*» — с лишней нотой.
  Cell cell;
};

/// Маркер смены темпа или размера в строке такта.
struct MarkView {
  /// Место смены в ударах от начала такта.
  double beat = 0.0;

  /// «было → стало»: «4/4 → 7/8», «120 → 150»; смена размера и темпа вместе —
  /// «3/4 → 4/4 · 120 → 150».
  std::string text;
};

/// Строка такта в окне.
struct BarView {
  /// Номер такта, «57».
  std::string label;

  /// Ударов в такте; шкала строки делится на них поровну.
  int beats = 4;

  /// Значения узлов по порядку мест.
  std::vector<ValueView> values;

  /// Удары, у которых нет значения на самом ударе: на их месте — точка.
  std::vector<int> dots;

  /// Удар, на котором сейчас воспроизведение, с 0; есть только у верхней
  /// строки и только во время воспроизведения.
  std::optional<int> currentBeat;

  /// Маркеры смен темпа и размера по порядку мест.
  std::vector<MarkView> marks;

  /// Узлов на удар в самом мелком режиме ударов такта; у верхней строки
  /// учитывается и текущий режим для ударов, которые ещё не начались. По нему
  /// окно выбирает кегль.
  int division = 1;

  /// Среднее, «+2.0», цвет — по окну попадания, когда воспроизведение ушло из
  /// такта; `Target` у среднего не бывает.
  /// Нет у верхней строки и у строки с одним значением или без значений.
  std::optional<Cell> mean;

  /// Разброс, «3.7», цвет `Neutral`; есть вместе с `mean`.
  std::optional<Cell> spread;
};

/// Готовит строки тактов окна из свода тактов (design.md D7, `timing-display`).
///
/// Строки — видимые строки свода сверху вниз: в их такт входило
/// воспроизведение, и они не свёрнуты паузой.
///
/// Отклонение ноты — целые миллисекунды, округлённые до ближайшего, со знаком:
/// «−» (U+2212) — раньше, «+» — позже, «0» — ноль. Цвет — по показанному
/// числу: не дальше 0.5 мс от смещения окна попадания — `Target`, иначе между
/// краями окна включительно — `Good`, иначе `Bad`. Окно значения —
/// запомненное в узле, когда значение появилось; окно среднего — когда
/// воспроизведение ушло из такта, и среднее бывает только `Good` или `Bad`.
/// Среднее и разброс — с одним знаком после
/// запятой. Темп в маркере — целое число четвертей в минуту или дробное с
/// одним-двумя знаками после запятой.
std::vector<BarView> present(const Bars &bars);

} // namespace training::grid
