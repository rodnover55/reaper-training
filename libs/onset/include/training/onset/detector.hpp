#pragma once

#include "training/onset/sliding_max.hpp"

#include <cstdint>
#include <span>
#include <vector>

namespace training::onset {

/// Параметры поиска атаки.
struct Settings {
  /// Частота дискретизации потока, Гц; больше нуля.
  double sampleRate = 44100.0;

  /// Порог тишины, dBFS: атака, у которой огибающая после ВЧ-фильтра не
  /// доходит до порога, не находится. Щелчок медиатора после ВЧ-фильтра тише
  /// пика всего сигнала: на тихом DI-входе — примерно на 30 дБ.
  double silenceDb = -50.0;

  /// Частота среза ВЧ-фильтра, Гц: звук ниже неё — гул и основной тон струны —
  /// в поиске атаки не участвует. Больше нуля и меньше половины частоты
  /// дискретизации.
  double highPassHz = 1000.0;

  /// Мёртвое время после начала атаки, мс: в течение него новых атак нет. Оно
  /// же отделяет щелчок медиатора от разгорающегося следом тела ноты.
  double deadTimeMs = 40.0;

  /// Во сколько раз огибающая должна подняться над своим максимумом за 25 мс,
  /// чтобы это была резкая атака; больше 1. 2 — это 6 дБ.
  double ratio = 2.0;

  /// Во сколько раз должна вырасти энергия верха спектра за 20 мс, чтобы
  /// подъём огибающей был ударом по звучащей струне; больше 1. 2 — удар
  /// добавил верха спектра не меньше, чем было в звоне. На записях DI-гитары
  /// годится любое значение от 1.4 до 4: ниже — ложные атаки на нарастающем
  /// после удара звоне, выше — пропуски слабых ударов.
  double energyRatio = 2.0;
};

/// Найденная атака.
struct Onset {
  /// Начало атаки — дробный номер сэмпла от начала потока: 0.0 — первый
  /// сэмпл после создания детектора или `reset()`.
  double position = 0.0;

  /// Уровень огибающей после ВЧ-фильтра, dBFS: у резкой атаки — в момент,
  /// когда её заметили, у удара по звучащей струне — наибольший за подъём, с
  /// которого он начался.
  double levelDb = 0.0;
};

/// Поиск атак в потоке сэмплов одного канала. Смотрит только на звук выше
/// ВЧ-фильтра: на огибающую (поднимается сразу, спадает за 10 мс) и на энергию
/// верха спектра за 20 мс.
///
/// Начало атаки — подъём огибающей над её максимумом за 25 мс: точка, где
/// огибающая пересекла этот максимум (или порог тишины, если он выше), линейно
/// между сэмплами. Подъём засчитывается атакой одним из двух путей:
///
/// - **Резкая атака** — огибающая поднялась в `ratio` раз над максимумом.
///   Атака сообщается в момент, когда огибающая перешла этот уровень. Так
///   находится нота после тишины, после заглушённой струны и громкий удар по
///   звучащей.
/// - **Удар по звучащей струне** — энергия верха спектра за 20 мс выросла в
///   `energyRatio` раз над наибольшей энергией 20-мс окон перед ними. Это удар, пик
///   которого выше звона меньше чем в `ratio` раз: шум медиатора держится
///   несколько миллисекунд, и энергию он поднимает сильнее, чем пик. Верх
///   спектра от медиатора приходит раньше щелчка, поэтому решение ждёт ещё
///   20 мс, и начало — самый сильный подъём за 20 мс до и после роста энергии.
///   Рост энергии без подъёма огибающей атакой не считается.
///
/// Энергия — сумма квадратов разности соседних сэмплов после ВЧ-фильтра, то
/// есть звук с весом, растущим с частотой. Верх спектра у струны затухает
/// быстрее всего, а медиатор даёт его заново, поэтому новый удар поднимает
/// такую энергию и тогда, когда пик огибающей почти не растёт.
///
/// Окна длиннее периода самой низкой ноты гитары — си 62 Гц, 16 мс. Звенящая
/// низкая струна даёт короткий ВЧ-всплеск раз в период: всплеск не выше
/// недавних, энергия за период почти постоянна, и звон атак не даёт.
/// Максимум огибающей берётся от 25 до 5 мс назад: последние 5 мс в окно не
/// входят, иначе нарастание атаки сравнивалось бы с самим собой.
///
/// Энергия сравнивается только по окнам, целиком лежащим после прошлой атаки и
/// после начала потока, — через 60 мс. Тело глушёной ноты, разгорающееся после
/// щелчка, поэтому за новый удар не принимается.
///
/// Поток подаётся кусками любой длины. Результат не зависит от того, как поток
/// нарезан: те же сэмплы дают те же атаки до последнего бита. Атака
/// сообщается в том же вызове `process`, в котором её заметили: резкая — в
/// первые миллисекунды нарастания, удар по звучащей струне — через 20–40 мс
/// после начала.
///
/// Рассчитан на чистый сигнал гитары. У сильно сжатого звука — перегруза —
/// удар по струне почти не поднимает огибающую, и атаки пропускаются.
///
/// Многопоточность: один экземпляр — один поток вызовов.
class Detector {
public:
  /// Создаёт детектор, готовый к началу потока. Выделяет память под историю
  /// огибающей и энергии за 40 мс; дальше `process` память выделяет только
  /// под `onsets`.
  explicit Detector(const Settings &settings);

  /// Начинает поток заново: забывает прошлые сэмплы, следующая позиция — 0.
  /// Нужен на разрыве потока, чтобы не склеить несмежные сэмплы.
  void reset();

  /// Меняет порог тишины, dBFS. Действует со следующего поданного сэмпла;
  /// поток не начинается заново.
  void setSilenceDb(double silenceDb);

  /// Меняет `Settings::energyRatio`. Действует со следующего поданного
  /// сэмпла; поток не начинается заново.
  void setEnergyRatio(double energyRatio);

  /// Обрабатывает следующий кусок потока и дописывает найденные в нём атаки в
  /// конец `onsets`, в порядке возрастания позиции. Прежнее содержимое
  /// `onsets` не трогает. Пустой кусок ничего не меняет.
  void process(std::span<const float> samples, std::vector<Onset> &onsets);

  /// Сколько сэмплов обработано с начала потока.
  std::uint64_t position() const { return position_; }

private:
  /// Значение огибающей или энергии на сэмпле `index`.
  struct Level {
    std::uint64_t index = 0;
    double value = 0.0;
  };

  /// Подъём огибающей над её максимумом за 25 мс: начался на сэмпле `index`,
  /// точка пересечения — `position`, наибольшее отношение огибающей к уровню
  /// за подъём — `value`, огибающая в этот момент — `envelope`.
  struct Rise {
    std::uint64_t index = 0;
    double value = 0.0;
    double position = 0.0;
    double envelope = 0.0;
  };

  void processSample(double sample, std::vector<Onset> &onsets);

  /// Записывает атаку с началом на сэмпле `index` (точка — `position`) и
  /// уровнем огибающей `envelope` и начинает после неё мёртвое время.
  void report(std::uint64_t index, double position, double envelope,
              std::vector<Onset> &onsets);

  // Коэффициенты ВЧ-фильтра второго порядка, нормированные на a0.
  double b0_ = 0.0;
  double b1_ = 0.0;
  double b2_ = 0.0;
  double a1_ = 0.0;
  double a2_ = 0.0;

  double release_ = 0.0;
  double threshold_ = 0.0;
  double ratio_ = 0.0;
  double energyRatio_ = 0.0;
  std::uint64_t deadTime_ = 0;

  // Окно максимума огибающей: от `backOldest_` до `backNewest_` сэмплов назад
  // включительно; `backNewest_` не меньше 1.
  std::uint64_t backOldest_ = 0;
  std::uint64_t backNewest_ = 0;

  // Окно энергии, сэмплов: 20 мс.
  std::uint64_t energyLength_ = 0;

  // Огибающая последних `backNewest_` сэмплов, кольцом по номеру сэмпла: в
  // окно максимума она входит, когда выходит отсюда.
  std::vector<double> recentEnvelope_;
  SlidingMax<Level> envelopeMax_;

  // Квадраты разности соседних сэмплов после фильтра за последние 20 мс и их
  // сумма — энергия окна, кольцом по номеру сэмпла.
  std::vector<double> squares_;
  double squaresSum_ = 0.0;

  // Энергия окон, кончающихся в последние 20 мс, кольцом по номеру сэмпла:
  // выходя отсюда, она становится опорой — окна, кончающиеся от 40 до 20 мс
  // назад.
  std::vector<double> recentEnergy_;
  SlidingMax<Level> energyMax_;

  // Подъёмы огибающей, начавшиеся за последние 40 мс, — кандидаты в начало
  // удара по звучащей струне. Текущий подъём — `rise_`, пока `rising_`.
  SlidingMax<Rise> rises_;
  Rise rise_;
  bool rising_ = false;

  // Энергия выросла, и на сэмпле `energyDecision_` решается, был ли удар.
  bool energyPending_ = false;
  std::uint64_t energyDecision_ = 0;

  // Состояние фильтра: прошлые два входа и выхода.
  double x1_ = 0.0;
  double x2_ = 0.0;
  double y1_ = 0.0;
  double y2_ = 0.0;

  double envelope_ = 0.0;
  std::uint64_t position_ = 0;

  // Первый сэмпл, с которого возможна следующая атака, и первый, с которого
  // окна энергии лежат после прошлой атаки и начала потока.
  std::uint64_t armedFrom_ = 0;
  std::uint64_t energyArmedFrom_ = 0;
};

} // namespace training::onset
