#pragma once

// Поставка звука входа в ядро (`hit-timing`, `input-calibration`).

#include "training/core/input/audio_block.hpp"
#include "training/core/types.hpp"

namespace training::core::input {

/// Приёмник звукового потока блоками: тренировка звука или калибровка.
///
/// Условия вызова:
/// - блоки идут с частотой дискретизации приёмника (`sampleRate`). Блоки
///   другой частоты вызывающий отдаёт новому приёмнику с этой частотой;
/// - блоки идут по времени. Начало нового блока, которое по времени совпадает
///   с уже полученным в том же запуске звуком, приёмник отбрасывает
///   (`SoundReceiver.receive#order`); запуск начинает время блоков заново.
///   Промежуток между концом прошлого блока и началом нового — пропущенный
///   звук, приёмник считает его тишиной.
///
/// Многопоточность: методы реализации можно звать из любых потоков
/// одновременно.
class SoundReceiver {
public:
  /// Позволяет удалять реализацию через указатель на `SoundReceiver`.
  virtual ~SoundReceiver() = default;

  /// Создаёт приёмник; своих данных у `SoundReceiver` нет, их хранит
  /// реализация.
  SoundReceiver() = default;

  /// Копирование запрещено: приёмник передаётся только по ссылке или указателю.
  SoundReceiver(const SoundReceiver &) = delete;

  /// Присваивание копией запрещено: приёмник передаётся
  /// только по ссылке или указателю.
  SoundReceiver &operator=(const SoundReceiver &) = delete;

  /// Перемещение запрещено: приёмник передаётся только по ссылке или указателю.
  SoundReceiver(SoundReceiver &&) = delete;

  /// Присваивание перемещением запрещено: приёмник передаётся
  /// только по ссылке или указателю.
  SoundReceiver &operator=(SoundReceiver &&) = delete;

  /// Частота дискретизации блоков, которые принимает приёмник: её задаёт
  /// создание реализации, и на всё время жизни приёмника она та же.
  virtual SampleRate sampleRate() const = 0;

  /// Принимает следующий блок сэмплов для обработки.
  virtual void receive(const AudioBlock &block) = 0;
};

} // namespace training::core::input
