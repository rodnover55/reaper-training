#pragma once

// Синтетическая гитара для тестов поиска атаки: щипки струны с заранее
// известным началом.

#include <cstddef>
#include <cstdint>
#include <vector>

namespace training::test {

/// Щипок струны.
struct Pluck {
  /// Номер сэмпла, с которого звучит щипок: первый ненулевой сэмпл щипка стоит
  /// ровно здесь.
  std::size_t start = 0;

  /// Частота основного тона, Гц; больше нуля и меньше половины частоты
  /// дискретизации.
  double frequency = 110.0;

  /// Наибольшая амплитуда возбуждения, доли полной шкалы.
  double amplitude = 0.5;

  /// Струна. Новый щипок той же струны глушит прошлый за 2 мс, как медиатор,
  /// упавший на звучащую струну; щипки разных струн звучат вместе.
  int string = 0;

  /// За сколько миллисекунд звук щипка нарастает до полной громкости: 0 —
  /// сразу, как от медиатора; больше — тело глушёной ноты, разгорающееся
  /// после щелчка.
  double riseMs = 0.0;
};

/// Что звучит, кроме щипков, и как звук искажается.
struct SynthSettings {
  double sampleRate = 48000.0;

  /// Белый шум, dBFS по пику; меньше −200 — шума нет.
  double noiseDb = -240.0;

  /// Гул 50 Гц, dBFS по пику; меньше −200 — гула нет.
  double humDb = -240.0;

  /// Сила перегруза: 0 — чистый звук, больше — мягкое ограничение
  /// `tanh(drive · x) / tanh(drive)`, звук плотнее и длиннее.
  double drive = 0.0;

  /// Во сколько раз за секунду затихает струна: 0.5 — вдвое.
  double decayPerSecond = 0.3;

  /// Зерно случайных чисел: одно зерно — один и тот же сигнал.
  std::uint32_t seed = 1;
};

/// Синтезирует `length` сэмплов: щипки по Карплусу — Стронгу, шум, гул и
/// перегруз из `settings`. Щипки могут идти в любом порядке.
std::vector<float> render(const std::vector<Pluck> &plucks, std::size_t length,
                          const SynthSettings &settings);

/// Удар по низкой струне, которую не глушат, — так её отдаёт DI-вход. Тон
/// затухает, а раз в период звукосниматель даёт короткий ВЧ-всплеск: излом
/// волны. Удар начинается с шума медиатора — пачки таких же всплесков, —
/// после неё струна звенит заново. Прошлый звон удар обрывает.
struct Strike {
  /// Первый сэмпл удара — начало первого всплеска пачки медиатора.
  std::size_t start = 0;

  /// Амплитуда тона после удара, доли полной шкалы.
  double amplitude = 0.05;

  /// Пик ВЧ-всплеска звона сразу после удара, доли полной шкалы.
  double burstAmplitude = 0.005;

  /// Пик всплесков пачки медиатора, доли полной шкалы; 0 — удар без пачки.
  double pickAmplitude = 0.01;
};

/// Звенящая струна: тон, всплески и пачка медиатора.
struct RingingSettings {
  double sampleRate = 48000.0;

  /// Частота тона, Гц: си, самая низкая нота семиструнной гитары.
  double frequency = 61.7;

  /// Во сколько раз за секунду затихает звон: 0.5 — вдвое.
  double decayPerSecond = 0.5;

  /// Всплеск — синусоида этой частоты, Гц, начинается с нуля и затихает в e
  /// раз за `burstMs`.
  double burstHz = 3000.0;
  double burstMs = 0.3;

  /// Пачка медиатора: столько всплесков через `pickSpacingMs`.
  int pickBursts = 5;
  double pickSpacingMs = 1.5;
};

/// Синтезирует `length` сэмплов звенящей струны с ударами `strikes`, по
/// возрастанию начала. До первого удара — тишина.
std::vector<float> renderRinging(const std::vector<Strike> &strikes, std::size_t length,
                                 const RingingSettings &settings);

/// Щипки ровной сеткой на одной струне: `count` нот через `interval` сэмплов,
/// первая — на `first`, частоты по кругу из `frequencies`, амплитуда
/// `amplitude`.
std::vector<Pluck> evenPlucks(std::size_t first, double interval, std::size_t count,
                              const std::vector<double> &frequencies, double amplitude);

} // namespace training::test
