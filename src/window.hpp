#pragma once

// Окно тренажёра (design.md D8, `timing-display`).

// SWELL объявляет max и min макросами, и они ломают стандартную библиотеку.
#define WDL_NO_DEFINE_MINMAX

#include <reaper_plugin.h>

#include <optional>

namespace training::reaper {

/// Модуль, в ресурсах которого лежат формы, — сам модуль расширения. Зовётся
/// при загрузке расширения до первого показа окна.
void setResourceModule(REAPER_PLUGIN_HINSTANCE module);

/// Открыто ли окно тренажёра.
bool windowShown();

/// Показывает окно тренажёра в доке REAPER, если оно закрыто, и закрывает,
/// если открыто. Где и закреплено ли окно, REAPER помнит сам по его
/// идентификатору. Зовётся из главного потока, после `initTrainer`.
void toggleWindow();

/// Перерисовывает строки и строку состояния открытого окна; закрытое не
/// трогает. Зовётся из главного потока.
void refreshWindow();

/// Показывает в контролах окна текущие настройки тренажёра — после того как
/// их поменяли не из окна, например действием режима.
void showSettings();

/// Закрывает окно, если оно открыто. Зовётся при выгрузке расширения, до
/// `shutdownTrainer`.
void closeWindow();

#ifdef TRAINING_DEBUG_BUILD
/// Нажимает флажок `control` открытого окна, как щелчок мышью: флажок
/// переключается, окно применяет настройку. Для проверок отладочной сборки.
/// Зовётся из главного потока.
///
/// @return новое состояние флажка; пусто, если окно закрыто или такого
///   контрола в нём нет.
std::optional<bool> clickCheckbox(int control);

/// Нажимает кнопку `control` открытого окна, как щелчок мышью: окно получает
/// BN_CLICKED и делает то же, что по щелчку. Скрытую и недоступную кнопку не
/// нажимает. Для проверок отладочной сборки. Зовётся из главного потока.
///
/// @return правда, если кнопка нажата; ложь, если окно закрыто или кнопки
///   нет, она скрыта или недоступна.
bool clickButton(int control);
#endif

#if defined(TRAINING_DEBUG_BUILD) && !defined(_WIN32)
/// Рисует строки тактов так же, как окно, но в память размером
/// `width`×`height` точек, без контролов, и пишет картинку в файл PPM `path`:
/// для проверок отладочной сборки, когда окно не видно на экране. Открывать
/// окно для этого не нужно. Зовётся из главного потока.
///
/// @return правда, если файл записан; ложь при пустом пути, неположительных
///   размерах или ошибке записи.
bool snapshotRows(const char *path, int width, int height);
#endif

} // namespace training::reaper
